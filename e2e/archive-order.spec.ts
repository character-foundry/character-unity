import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

for (const [profile, origin] of [['local', 'http://127.0.0.1:19310'], ['browser', 'http://127.0.0.1:19311'], ['hub', 'http://127.0.0.1:19312']] as const) {
  test(`${profile}: indexed browsing preserves the submitted numeric order across pages and supports date ordering and exact import`, async ({ page }, info) => {
    if (profile === 'hub') await page.setViewportSize({ width: 390, height: 844 });
    const searches: URL[] = [], errors: string[] = [];
    page.on('request', (request) => { if (new URL(request.url()).pathname.endsWith('/search')) searches.push(new URL(request.url())); });
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(origin);
    if (profile === 'hub') {
      const accounts = JSON.parse(await readFile('runtime/e2e-hub-accounts.json', 'utf8'));
      await page.getByLabel('Access key').fill(accounts.Alice.key); await page.getByRole('button', { name: 'Sign in', exact: true }).click();
      await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
    } else if (profile === 'local') await page.getByRole('button', { name: 'Connect to local library' }).click();
    await page.getByLabel('New workspace', { exact: true }).fill(`Indexed ${profile}`);
    await page.getByRole('button', { name: 'Create workspace' }).click();
    await page.getByRole('button', { name: 'Browse Archive', exact: true }).click();
    const panel = page.getByRole('region', { name: 'Archive import', exact: true });
    await panel.getByLabel('Search mode').selectOption('indexed');
    await expect(panel.getByLabel('Search Archive', { exact: true })).toHaveCount(0);
    await expect(panel.getByRole('button', { name: 'Search', exact: true })).toBeEnabled();
    await panel.getByLabel('Result order').selectOption('tokens_desc');
    await panel.getByLabel('Provider', { exact: true }).fill('synthetic');
    await panel.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(panel.getByText('Indexed results: 13 matches · 10 shown.')).toBeVisible();
    await expect(panel.getByRole('checkbox').first()).toHaveAccessibleName('Lexical 13');
    await expect(panel.getByRole('checkbox').last()).toHaveAccessibleName('Lexical 04');
    await panel.getByRole('checkbox', { name: 'Lexical 13', exact: true }).check();
    await panel.getByLabel('Result order').selectOption('tokens_asc');
    await panel.getByLabel('Advanced filter', { exact: true }).fill('tokenCount > 1000');
    await panel.getByRole('button', { name: 'Load more from Archive' }).click();
    await expect(panel.getByText('Indexed results: 13 matches · 13 shown.')).toBeVisible();
    await expect(panel.getByRole('checkbox').last()).toHaveAccessibleName('Lexical 01');
    expect(searches.at(-1)!.searchParams.get('mode')).toBe('browse');
    expect(searches.at(-1)!.searchParams.get('text')).toBe('');
    expect(searches.at(-1)!.searchParams.get('sort')).toBe('tokens_desc');
    expect(searches.at(-1)!.searchParams.get('filter') || '').toBe('');
    await panel.getByRole('checkbox', { name: 'Lexical 01', exact: true }).check();
    await panel.getByRole('button', { name: 'Review selection (2)', exact: true }).click();
    const review = panel.getByRole('region', { name: 'Selected originals', exact: true });
    await expect(review.getByRole('listitem')).toHaveCount(2);
    await expect(review).toContainText('Lexical 01'); await expect(review).toContainText('Lexical 13');
    await panel.getByRole('button', { name: 'Import selected originals', exact: true }).click();
    await expect(panel.getByText('Imported 2 of 2 selected originals.')).toBeVisible();
    await panel.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(panel.getByText('Indexed results: 3 matches · 3 shown.')).toBeVisible();
    await expect(panel.getByRole('checkbox').first()).toHaveAccessibleName('Lexical 11');
    await panel.getByLabel('Advanced filter', { exact: true }).fill('');
    await panel.getByLabel('Result order').selectOption('create_old');
    await panel.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(panel.getByRole('checkbox').first()).toHaveAccessibleName('Lexical 13');
    await panel.getByLabel('Result order').selectOption('create_new');
    await panel.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(panel.getByRole('checkbox').first()).toHaveAccessibleName('Lexical 01');
    await panel.getByLabel('Search mode').selectOption('lexical');
    await panel.getByLabel('Search Archive', { exact: true }).fill('forest OR ocean');
    await panel.getByLabel('Result order').selectOption('tokens_desc');
    await panel.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(panel.getByText('Card text results for “forest OR ocean”: 13 matches · 10 shown.')).toBeVisible();
    await expect(panel.getByRole('checkbox').first()).toHaveAccessibleName('Lexical 13');
    await panel.getByLabel('Search mode').scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`ordered-${profile}.png`) });
    expect(errors).toEqual([]);
  });
}

test('withdrawing indexed browsing or a selected field order never silently substitutes a query', async ({ page }) => {
  let allowOrder = true, allowBrowse = true, searches = 0;
  page.on('request', (request) => { if (new URL(request.url()).pathname.endsWith('/search')) searches++; });
  await page.route('**/api/archive/v1/status', async (route) => {
    const response = await route.fetch(), data = await response.json();
    if (!allowOrder) data.sorts = [];
    if (!allowBrowse) delete data.browse;
    await route.fulfill({ response, json: data });
  });
  await page.goto('http://127.0.0.1:19311');
  await page.getByLabel('New workspace', { exact: true }).fill('Ordering capability');
  await page.getByRole('button', { name: 'Create workspace' }).click();
  await page.getByRole('button', { name: 'Browse Archive', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Archive import', exact: true });
  await panel.getByLabel('Search mode').selectOption('indexed');
  await panel.getByLabel('Result order').selectOption('tokens_desc');
  allowOrder = false;
  await panel.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('This result order is no longer available');
  await expect(panel.getByLabel('Result order')).toHaveValue('tokens_desc');
  await expect(panel.getByRole('checkbox')).toHaveCount(0); expect(searches).toBe(0);
  await panel.getByLabel('Result order').selectOption('id');
  await panel.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(panel.getByText('Indexed results: 16 matches · 10 shown.')).toBeVisible();
  expect(searches).toBe(1);
  allowBrowse = false;
  await panel.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('Indexed browsing is no longer available');
  await expect(panel.getByRole('checkbox')).toHaveCount(0); expect(searches).toBe(1);
  await expect(panel.getByLabel('Search mode')).toHaveValue('metadata');
});
