import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('standalone browser JSON creates, saves offline, exports exact history and forks privately with no server calls', async ({ page,context },info) => {
  const api: string[] = [], errors: string[] = [];
  page.on('request',(request) => { if (new URL(request.url()).pathname.startsWith('/api/')) api.push(request.url()); });
  page.on('pageerror',(error) => errors.push(error.message));
  const original = { name: 'Browser preset',instruction: 'Private offline instructions',future: { keep: [1,null,true] } };
  const text = JSON.stringify(original,null,2);
  await page.goto('/'); await page.getByRole('link',{ name: 'Content',exact: true }).click();
  await page.getByRole('button',{ name: 'Presets',exact: true }).click();
  await page.getByRole('button',{ name: 'Create JSON',exact: true }).click();
  const dialog = page.getByRole('dialog',{ name: 'Create standalone JSON content',exact: true });
  await dialog.getByLabel('New content JSON',{ exact: true }).fill(text);
  await dialog.getByRole('button',{ name: 'Create from this JSON',exact: true }).click();
  await expect(page.getByRole('heading',{ name: original.name,exact: true })).toBeVisible();
  await context.setOffline(true);
  const changed = { ...original,instruction: 'Changed offline',future: { ...original.future,alsoKeep: 'Unknown field' } };
  await page.getByLabel('Content JSON',{ exact: true }).fill(JSON.stringify(changed,null,2));
  await page.getByRole('button',{ name: 'Save content revision',exact: true }).click();
  await expect(page.getByText('preset · saved head revision 2',{ exact: false })).toBeVisible();
  await context.setOffline(false); await page.reload();
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue(JSON.stringify(changed,null,2));
  const originalDownload = page.waitForEvent('download'); await page.getByRole('button',{ name: 'Download original',exact: true }).click();
  expect((await readFile((await (await originalDownload).path())!)).toString()).toBe(text);
  const exportDownload = page.waitForEvent('download'); await page.getByRole('button',{ name: 'Export selected JSON',exact: true }).click();
  expect(JSON.parse((await readFile((await (await exportDownload).path())!)).toString())).toEqual(changed);
  await page.getByLabel('Content revision',{ exact: true }).selectOption({ label: 'Revision 1 · Browser preset' });
  await page.getByRole('button',{ name: 'Fork selected revision',exact: true }).click();
  await expect(page.getByText('preset · saved head revision 1 · owned fork',{ exact: true })).toBeVisible();
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue(text);
  await expect(page.getByText('Sharing requires a configured server; browser-owned content stays private.',{ exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('native-browser-content-editor.png') });
  await page.getByRole('button',{ name: 'Back to content',exact: false }).click();
  await expect(page.getByText('2 presets in this workspace',{ exact: true })).toBeVisible();
  await page.getByRole('button',{ name: 'Browse shared',exact: true }).click();
  await expect(page.getByText('Browser-owned content remains private.',{ exact: false })).toBeVisible();
  await page.setViewportSize({ width: 375,height: 812 });
  await page.screenshot({ path: info.outputPath('native-browser-content-private-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(api).toEqual([]); expect(errors).toEqual([]);
});

test('browser-owned raw JSON rejects numeric precision loss before import and before Save without losing the draft', async ({ page }) => {
  const api: string[] = [];
  page.on('request',(request) => { if (new URL(request.url()).pathname.startsWith('/api/')) api.push(request.url()); });
  await page.goto('/content?kind=preset');
  await page.getByRole('button',{ name: 'Create JSON',exact: true }).click();
  const dialog = page.getByRole('dialog',{ name: 'Create standalone JSON content',exact: true });
  await dialog.getByLabel('New content JSON',{ exact: true }).fill('{"name":"Browser unsafe","opaque":9007199254740991.1}');
  await dialog.getByRole('button',{ name: 'Create from this JSON',exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('cannot be preserved without rounding');
  await dialog.getByLabel('New content JSON',{ exact: true }).fill('{"name":"Browser safe","opaque":9007199254740991}');
  await dialog.getByRole('button',{ name: 'Create from this JSON',exact: true }).click();
  await expect(page.getByRole('heading',{ name: 'Browser safe',exact: true })).toBeVisible();
  const edited = '{"name":"Browser safe","opaque":9007199254740991.1}';
  await page.getByLabel('Content JSON',{ exact: true }).fill(edited);
  await page.getByRole('button',{ name: 'Save content revision',exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('cannot be preserved without rounding');
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue(edited);
  await expect(page.getByText('preset · saved head revision 1',{ exact: false })).toBeVisible();
  await expect(page.getByRole('button',{ name: 'Save content revision',exact: true })).toBeEnabled();
  expect(api).toEqual([]);
});
