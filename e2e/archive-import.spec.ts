import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

for (const [profile, origin] of [['local', 'http://127.0.0.1:19310'], ['browser', 'http://127.0.0.1:19311']]) {
  test(`${profile}: selected Archive subset opens in Architect, saves and keeps source bytes`, async ({ page }, info) => {
    if (profile === 'browser') await page.setViewportSize({ width: 390, height: 844 });
    const writesToArchive: string[] = [], errors: string[] = [];
    page.on('request', (request) => { if (request.url().startsWith('http://127.0.0.1:19313') && request.method() !== 'GET') writesToArchive.push(request.method()); });
    page.on('pageerror', (error) => errors.push(error.message));
    const before = await page.request.get('http://127.0.0.1:19313/api/archive/v1/status');
    const snapshot = await before.json();
    const record = await (await page.request.get(`http://127.0.0.1:19313/api/archive/v1/cards/aster?snapshot=${snapshot.snapshot}`)).json();
    const original = await (await page.request.get(`http://127.0.0.1:19313/api/archive/v1/originals/${record.card.original.hash}?snapshot=${snapshot.snapshot}`)).body();
    await page.goto(origin!);
    if (profile === 'local') await page.getByRole('button', { name: 'Connect to local library' }).click();
    await page.getByLabel('New workspace', { exact: true }).fill(`Archive ${profile}`);
    await page.getByRole('button', { name: 'Create workspace' }).click();
    await page.getByRole('button', { name: 'Browse Archive', exact: true }).click();
    const archive = page.getByRole('region', { name: 'Archive import', exact: true });
    await expect(archive.getByRole('checkbox', { name: 'Aster', exact: true })).toBeVisible();
    await archive.getByLabel('Search Archive', { exact: true }).fill('nothing matches');
    await archive.getByRole('button', { name: 'Search', exact: true }).click();
    await expect(archive.getByText('No Archive cards match these filters.')).toBeVisible();
    await archive.getByLabel('Search Archive', { exact: true }).fill('');
    await archive.getByLabel('Provider', { exact: true }).fill('fixture');
    await archive.getByLabel('Tag', { exact: true }).fill('demo');
    await archive.getByRole('button', { name: 'Search', exact: true }).click();
    await archive.getByRole('checkbox', { name: 'Aster', exact: true }).check();
    await archive.getByRole('checkbox', { name: 'Cinder', exact: true }).check();
    await archive.getByRole('button', { name: 'Review selection (2)', exact: true }).click();
    const review = archive.getByRole('region', { name: 'Selected originals', exact: true });
    await expect(review).toContainText('Aster'); await expect(review).toContainText('Cinder'); await expect(review).not.toContainText('Birch');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await review.scrollIntoViewIfNeeded();
    await page.screenshot({ path: info.outputPath(`archive-${profile}-selection.png`), fullPage: false });
    await archive.getByRole('button', { name: 'Import selected originals', exact: true }).click();
    await expect(archive.getByText('Imported 2 of 2 selected originals.')).toBeVisible();
    const library = page.getByRole('complementary', { name: 'Character library', exact: true });
    await expect(library.getByRole('button', { name: 'Open aster', exact: true })).toBeVisible();
    await expect(library.getByRole('button', { name: 'Open cinder', exact: true })).toBeVisible();
    await expect(library.getByRole('button', { name: 'Open birch', exact: true })).toHaveCount(0);
    const editor = page.getByRole('region', { name: 'Editor 1', exact: true });
    await expect(editor.getByLabel('Name', { exact: true })).toHaveValue('aster');
    await editor.getByRole('button', { name: 'Character', exact: true }).click();
    await editor.getByLabel('Description', { exact: true }).fill('An edited Archive copy.');
    await editor.getByRole('button', { name: 'Save revision' }).click();
    await expect(editor.getByRole('status')).toHaveText('Saved');
    await editor.getByLabel('Description', { exact: true }).fill('This is still an unsaved draft.');
    const savedDownload = page.waitForEvent('download');
    await editor.getByRole('button', { name: 'Download saved revision', exact: true }).click();
    const exported = JSON.parse(await readFile((await (await savedDownload).path())!, 'utf8'));
    expect(exported.data.description).toBe('An edited Archive copy.');
    expect(exported.data.extensions.foundry.lineage.operation).toBe('edit');
    await expect(editor.getByLabel('Description', { exact: true })).toHaveValue('This is still an unsaved draft.');
    await editor.getByLabel('Description', { exact: true }).fill('An edited Archive copy.');

    const download = page.waitForEvent('download');
    await editor.getByRole('button', { name: 'Download accepted original' }).click();
    expect(await readFile((await (await download).path())!)).toEqual(original);
    await archive.getByRole('button', { name: 'Close Archive browser' }).click();
    await page.reload();
    await page.getByRole('combobox', { name: 'Workspace', exact: true }).selectOption({ label: `Archive ${profile}` });
    await page.getByRole('button', { name: 'Open aster', exact: true }).click();
    await editor.getByRole('button', { name: 'Character', exact: true }).click();
    await expect(editor.getByLabel('Description', { exact: true })).toHaveValue('An edited Archive copy.');
    expect(await (await page.request.get('http://127.0.0.1:19313/api/archive/v1/status')).json()).toEqual(snapshot);
    expect(writesToArchive).toEqual([]); expect(errors).toEqual([]);
  });
}
