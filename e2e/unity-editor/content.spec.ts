import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { expect, screenshot, test } from './fixtures.js';

test('standalone content imports exact JSON, keeps raw edits and history isolated, and shares only the reviewed saved revision', async ({ page },info) => {
  const name = `Preset ${randomUUID()}`, original = { name,temperature: 0.7,unknown: { original: 'keep every field' } };
  const bytes = Buffer.from(`\uFEFF${JSON.stringify(original,null,2)}\n`);
  await page.goto('/');
  await page.getByRole('link',{ name: 'Content',exact: true }).click();
  await page.getByRole('button',{ name: 'Presets',exact: true }).click();
  await expect(page.getByRole('heading',{ name: 'Lorebooks, presets & personas',exact: true })).toBeVisible();
  const chooser = page.waitForEvent('filechooser'), imported = page.waitForResponse((response) => response.url().includes('/api/content/') && response.url().includes('/imports?') && response.request().method() === 'POST');
  await page.getByRole('button',{ name: 'Import preset JSON',exact: true }).click();
  await (await chooser).setFiles({ name: 'preset.json',mimeType: 'application/json',buffer: bytes });
  const response = await imported; expect(response.status(),await response.text()).toBe(201);
  const initial = await response.json() as { record: { document: { id: string }; revision: { id: string } } };
  await expect(page.getByRole('heading',{ name,exact: true })).toBeVisible();
  const download = page.waitForEvent('download'); await page.getByRole('button',{ name: 'Download original',exact: true }).click();
  expect(await readFile((await (await download).path())!)).toEqual(bytes);
  const changed = { ...original,temperature: 1,unknown: { ...original.unknown,added: 'saved edit' } };
  await page.getByLabel('Content JSON',{ exact: true }).fill(JSON.stringify(changed,null,2));
  const saved = page.waitForResponse((received) => received.url().endsWith(`/documents/${initial.record.document.id}`) && received.request().method() === 'PUT');
  await page.getByRole('button',{ name: 'Save content revision',exact: true }).click(); expect((await saved).status()).toBe(200);
  await expect(page.getByText('preset · saved head revision 2',{ exact: false })).toBeVisible();
  await page.getByLabel('Content JSON',{ exact: true }).fill(JSON.stringify({ ...changed,unsaved: 'must not publish' },null,2));
  await page.getByLabel('Content revision',{ exact: true }).selectOption(initial.record.revision.id);
  await expect(page.getByRole('button',{ name: 'Review sharing',exact: true })).toBeEnabled();
  const exported = page.waitForEvent('download'); await page.getByRole('button',{ name: 'Export selected JSON',exact: true }).click();
  expect(JSON.parse((await readFile((await (await exported).path())!)).toString())).toEqual(original);
  await page.getByRole('button',{ name: 'Review sharing',exact: true }).click();
  const dialog = page.getByRole('dialog',{ name: 'Review standalone content publication',exact: true });
  await expect(dialog.getByLabel('Exact JSON selected for sharing')).toContainText('keep every field');
  await expect(dialog.getByLabel('Exact JSON selected for sharing')).not.toContainText('saved edit');
  await expect(dialog.getByLabel('Exact JSON selected for sharing')).not.toContainText('must not publish');
  await expect(dialog.getByLabel('Content visibility',{ exact: true })).toHaveValue('private');
  await expect(dialog.getByRole('button',{ name: 'Publish selected revision',exact: true })).toBeDisabled();
  await screenshot(page,info,'native-content-exact-review');
  await dialog.getByRole('checkbox',{ name: 'I reviewed this exact JSON and its sharing permissions.',exact: true }).check();
  await dialog.getByRole('button',{ name: 'Publish selected revision',exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('published with private visibility');
  await dialog.getByRole('button',{ name: 'Done',exact: true }).click();
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue(/must not publish/);
  await screenshot(page,info,'native-content-editor-desktop');
  await page.setViewportSize({ width: 375,height: 812 });
  await expect(page.getByRole('heading',{ name,exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await screenshot(page,info,'native-content-editor-mobile');
  await page.getByRole('button',{ name: 'Back to content',exact: false }).click();
  await page.getByRole('button',{ name: 'My shared items',exact: true }).click();
  await page.getByRole('button').filter({ hasText: name }).click();
  await expect(page.getByLabel('Shared content JSON')).toContainText('keep every field');
  await expect(page.getByLabel('Shared content JSON')).not.toContainText('saved edit');
  await screenshot(page,info,'native-content-shared-mobile');
  await page.getByLabel('Content visibility',{ exact: true }).selectOption('public');
  await page.getByRole('checkbox',{ name: 'Allow private forks',exact: true }).check();
  await page.getByRole('button',{ name: 'Save version-checked policy',exact: true }).click();
  await expect(page.getByText('Shared revision 1 · policy version 2',{ exact: true })).toBeVisible();
  await page.getByLabel('Content visibility',{ exact: true }).selectOption('private');
  await page.getByRole('checkbox',{ name: 'Allow private forks',exact: true }).uncheck();
  await page.getByRole('button',{ name: 'Save version-checked policy',exact: true }).click();
  await expect(page.getByText('Shared revision 1 · policy version 3',{ exact: true })).toBeVisible();
  await page.getByRole('button',{ name: 'Save private fork to this workspace',exact: true }).click();
  await expect(page.getByText('preset · saved head revision 1 · owned fork',{ exact: true })).toBeVisible();
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue(JSON.stringify(original,null,2));
  page.once('dialog',async (dialog) => { await dialog.accept(); }); await page.getByRole('button',{ name: 'Remove content',exact: true }).click();
  await expect(page.getByRole('heading',{ name: 'Lorebooks, presets & personas',exact: true })).toBeVisible();
});

test('standalone raw-only lorebooks, invalid drafts, dedupe notices and recovery stay explicit', async ({ page,diagnostics },info) => {
  const name = `Risu lorebook ${randomUUID()}`, value = { type: 'risu',name,unknown: { preserve: ['opaque',1,null] } };
  const bytes = Buffer.from(JSON.stringify(value));
  const workspaceName = `Content recovery ${randomUUID()}`;
  await page.goto('/');
  await page.getByRole('button',{ name: 'Account and workspace',exact: true }).click();
  await page.getByRole('button',{ name: 'New workspace',exact: true }).click();
  await page.getByLabel('Workspace name',{ exact: true }).fill(workspaceName);
  const created = page.waitForResponse((response) => response.url().endsWith('/api/workspaces') && response.request().method() === 'POST');
  await page.getByRole('button',{ name: 'Create workspace',exact: true }).click(); expect((await created).status()).toBe(201);
  await page.getByRole('link',{ name: 'Content',exact: true }).click();
  const chooser = page.waitForEvent('filechooser'); await page.getByRole('button',{ name: 'Import lorebook JSON',exact: true }).click();
  await (await chooser).setFiles({ name: 'risu.json',mimeType: 'application/json',buffer: bytes });
  await expect(page.getByRole('heading',{ name,exact: true })).toBeVisible();
  await expect(page.getByText('This format is kept as raw JSON.',{ exact: false })).toBeVisible();
  await page.getByLabel('Content JSON',{ exact: true }).fill('{invalid but recoverable');
  diagnostics.expectedStatuses.add(400);
  await page.getByRole('button',{ name: 'Save content revision',exact: true }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  page.once('dialog',async (dialog) => { await dialog.accept(); }); await page.reload();
  await expect(page.getByRole('button',{ name: 'Account and workspace',exact: true })).toHaveAttribute('title',`Local owner · ${workspaceName}`);
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue('{invalid but recoverable');
  await expect(page.getByRole('status').filter({ hasText: 'Recovered this account/workspace' })).toBeVisible();
  await screenshot(page,info,'native-content-invalid-recovery');
  page.once('dialog',async (dialog) => { await dialog.accept(); }); await page.getByRole('button',{ name: 'Reload saved head',exact: true }).click();
  await expect(page.getByLabel('Content JSON',{ exact: true })).toHaveValue(/preserve/);
  await page.getByRole('button',{ name: 'Back to content',exact: false }).click();
  const again = page.waitForEvent('filechooser'); await page.getByRole('button',{ name: 'Import lorebook JSON',exact: true }).click();
  await (await again).setFiles({ name: 'same.json',mimeType: 'application/json',buffer: bytes });
  await expect(page.getByRole('status').filter({ hasText: 'Already in your library; no duplicate stored.' })).toBeVisible();
});

